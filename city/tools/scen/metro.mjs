import { startTrial, st } from './lib.mjs';
const until = async (p, fn, maxS) => { for (let i = 0; i < maxS * 2; i++) { await p.waitForTimeout(500); const r = await p.evaluate(fn); if (r) return r; } return null; };
const pick = (p, txt) => p.evaluate((txt) => { const b = [...document.querySelectorAll('#card button.item, #card button[data-to]')].find(b => b.textContent.includes(txt) && !b.disabled); if (b) b.click(); return b ? b.textContent : null; }, txt);
const walkObj = (p, pred) => p.evaluate((pred) => { const G = NLS.G, L = G.S.loc; const I = NLS.nav.interiorOf(G, L.b, L.floor).I; const o = I.objs.find(new Function('o', 'return ' + pred)); if (o) NLS.nav.navTo({ kind: 'obj', o }); return !!o; }, pred);
const toast = (p) => p.evaluate(() => document.getElementById('toast').textContent);
export default async (p, shot) => {
  await startTrial(p);
  const nm = await p.evaluate(() => { globalThis.__NAVSPEED = 3; const G = NLS.G, b = G.world.map.buildings.find(b => b.type === 'metro' && G.tr.byId.RING.stops.some(s => s.id === b.stationId)); const L = G.S.loc; L.k = 'out'; delete L.b; delete L.floor; L.x = b.doorX + 0.5; L.y = b.doorY + 0.6; G.S.min = 9 * 60; NLS.U.cwAt = -999; NLS.nav.navTo({ kind: 'bld', b: b.idx }); return b.name + ' ' + b.idx; });
  console.log('entrance', nm);
  await p.waitForTimeout(800); await shot('entrance_out');
  await until(p, () => NLS.G.S.loc.k === 'in' && !NLS.nav.NAV, 30);
  console.log('in', JSON.stringify(await st(p)).slice(0, 100));
  await p.evaluate(() => NLS.nav.navTo({ kind: 'floor', floor: -1 }));
  await until(p, () => NLS.G.S.loc.floor === -1 && !NLS.nav.NAV && !NLS.G.S.loc.tr, 40);
  await shot('b1_concourse');
  await walkObj(p, "o.act==='fx_stticket'"); await until(p, () => NLS.U.modal, 30);
  await pick(p, '行き先を選んで'); await p.waitForTimeout(500);
  console.log('dest list:', (await st(p)).card.slice(0, 260).replace(/\n/g, ' | '));
  console.log('bought:', await pick(p, '東都タワー前'), await toast(p));
  await p.evaluate(() => NLS.nav.navTo({ kind: 'floor', floor: -2 }));
  await until(p, () => NLS.G.S.loc.floor === -2 && !NLS.nav.NAV && !NLS.G.S.loc.tr, 60);
  console.log('platform', JSON.stringify(await st(p)).slice(0, 100), 'railIn', await p.evaluate(() => NLS.G.S.railIn));
  await p.waitForTimeout(8000); await shot('b2_platform');
  await walkObj(p, "o.act==='fx_stboard'"); await until(p, () => NLS.U.modal, 30);
  console.log('board:', (await st(p)).card.replace(/\n/g, ' | '));
  await pick(p, '列車に乗る'); await p.waitForTimeout(1500); await shot('riding');
  await p.evaluate(() => document.querySelector('#ridebar [data-a=skip]')?.click());
  await until(p, () => !document.getElementById('ride').classList.contains('on'), 60);
  console.log('arrived', JSON.stringify(await st(p)).slice(0, 120), await toast(p));
  await shot('arrival');
};
